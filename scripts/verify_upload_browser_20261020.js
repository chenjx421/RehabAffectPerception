// Synthetic browser acceptance; secrets remain in memory and never in screenshots.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { chromium } = require('playwright');
const root = path.resolve(__dirname, '..');
const runtime = path.join(root, '.runtime');
const read = file => JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, ''));
const state = read(path.join(runtime, 'manager_share_state.json'));
const fixture = process.argv[2];
if (!fixture || !path.basename(fixture).startsWith('SYNTHETIC-')) throw new Error('synthetic_fixture_required');
const out = path.join(runtime, 'browser_upload_acceptance_20261020');
fs.mkdirSync(out, { recursive: true });
const report = { checked_at: new Date().toISOString(), origin: state.origin, synthetic_only: true, passed: false, checks: [], errors: [] };
const save = () => fs.writeFileSync(path.join(out, 'report.json'), JSON.stringify(report, null, 2));
function check(value, code) { if (!value) { const error = new Error(code); error.safeCode = code; throw error; } report.checks.push(code); save(); }
let browser, step = 'login';
(async () => {
  const rows = fs.readFileSync(path.join(runtime, 'demo2_pilot_accounts_20260908.md'), 'utf8').split(/\r?\n/);
  const row = rows.map(line => line.split('|').map(v => v.trim())).find(row => row[2] === 't1');
  check(!!row?.[3], 'credential_available');
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
  const page = await context.newPage();
  page.setDefaultTimeout(60000);
  page.on('pageerror', error => report.errors.push({ step, type: error.name }));
  await page.goto(state.invite_url, { waitUntil: 'domcontentloaded' });
  await page.waitForURL(state.origin + '/demo2/login');
  await page.locator('#username').fill('t1');
  await page.locator('#password').fill(row[3]);
  await page.locator('#loginButton').click();
  await page.waitForURL(state.origin + '/demo2/school');
  const course = 'SYNTHETIC-browser-upload-' + Date.now();
  report.course_id = course;
  await page.goto(state.origin + '/demo2/upload?course_id=' + course);
  await page.waitForFunction(() => workspace && !workspaceLoading);
  step = 'upload_and_retry';
  await page.locator('#courseName').fill('Synthetic upload reliability test');
  await page.locator('#videoFile').setInputFiles(fixture);
  let attempts = 0;
  await page.route('**/api/v1/demo2/upload/chunks?*', async route => {
    attempts++;
    if (attempts === 1) return route.abort('failed');
    await route.continue();
  });
  const cdp = await context.newCDPSession(page);
  await cdp.send('Network.enable');
  await cdp.send('Network.emulateNetworkConditions', { offline: false, latency: 80, downloadThroughput: 2 * 1024 * 1024, uploadThroughput: 512 * 1024 });
  await page.locator('#uploadButton').click();
  await page.waitForFunction(() => uploadSession?.acknowledged >= 4194304, null, { timeout: 180000 });
  check(attempts >= 2, 'failed_request_retried');
  report.task_id = await page.evaluate(() => uploadSession.taskId);
  step = 'pause';
  await page.locator('#pauseUploadButton').click();
  await page.waitForFunction(() => uploadSession?.paused && !uploadSession.running);
  const paused = await page.evaluate(() => ({ bytes: uploadSession.acknowledged, next: uploadSession.next }));
  check(paused.bytes >= 4194304 && paused.bytes < fs.statSync(fixture).size, 'pause_preserves_partial_progress');
  await page.screenshot({ path: path.join(out, '01-paused.png'), fullPage: true });
  step = 'reload_and_resume';
  page.on('dialog', dialog => dialog.accept());
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => workspace && !workspaceLoading);
  const resume = page.locator('[data-resume-task="' + report.task_id + '"]');
  check(await resume.count() === 1, 'resume_action_after_reload');
  const chooser = page.waitForEvent('filechooser');
  await resume.click();
  await (await chooser).setFiles(fixture);
  await page.waitForFunction(() => uploadSession && uploadSession.acknowledged >= 4194304);
  check(await page.evaluate(() => uploadSession.taskId) === report.task_id, 'resume_keeps_same_task');
  await page.waitForFunction(() => uploadSession === null && document.getElementById('progressPercent').textContent === '100%', null, { timeout: 240000 });
  await cdp.send('Network.emulateNetworkConditions', { offline: false, latency: 0, downloadThroughput: -1, uploadThroughput: -1 });
  const response = await context.request.get(state.origin + '/api/v1/demo2/upload/task?id=' + report.task_id);
  const task = (await response.json()).task;
  const expected = crypto.createHash('sha256').update(fs.readFileSync(fixture)).digest('hex');
  check(task.upload_status === 'completed' && task.sha256 === expected, 'completed_hash_matches_original');
  check(await page.locator('.task-row').count() === 1, 'no_duplicate_task');
  await page.screenshot({ path: path.join(out, '02-complete.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'mobile_no_horizontal_overflow');
  await page.screenshot({ path: path.join(out, '03-mobile.png'), fullPage: true });
  check(report.errors.length === 0, 'no_browser_script_errors');
  report.passed = true;
})().catch(error => { report.failure = { step, code: error.safeCode || 'browser_or_network_failure', type: error.name }; process.exitCode = 1; }).finally(async () => {
  if (browser) await browser.close();
  save(); console.log(JSON.stringify(report, null, 2));
});
