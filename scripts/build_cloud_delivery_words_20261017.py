def base(title, subtitle):
    d = Document()
    s = d.sections[0]
    s.page_width, s.page_height = Inches(8.5), Inches(11)
    s.top_margin, s.bottom_margin = Inches(.62), Inches(.60)
    s.left_margin, s.right_margin = Inches(.72), Inches(.72)
    s.header_distance, s.footer_distance = Inches(.23), Inches(.25)
    for name, size, bold in [('Normal', 11, False), ('Title', 20, True),
                             ('Heading 1', 15, True), ('Heading 2', 12, True)]:
        font(d.styles[name], size, bold)
    for el in list(d.styles.element.iter(qn('w:pBdr'))):
        el.getparent().remove(el)
    pf = d.styles['Normal'].paragraph_format
    pf.line_spacing, pf.space_after, pf.widow_control = 1.14, Pt(5), True
    for name in ('Heading 1', 'Heading 2'):
        p = d.styles[name].paragraph_format
        p.space_before, p.space_after, p.keep_with_next = Pt(8), Pt(4), True
    d.styles['Title'].paragraph_format.space_after = Pt(7)
    footer = s.footer.paragraphs[0]
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    field = OxmlElement('w:fldSimple')
    field.set(qn('w:instr'), 'PAGE')
    footer._p.append(field)
    d.core_properties.title = title
    d.core_properties.author = ''
    d.core_properties.last_modified_by = ''
    d.add_paragraph(title, 'Title')
    para(d, subtitle, small=True)
    return d


def h(d, title):
    d.add_heading(title, 2)


def page(d, title):
    p = d.add_heading(title, 1)
    p.paragraph_format.page_break_before = True


def p(d, text):
    return para(d, text)


def note(d, text):
    return para(d, text, small=True)


def pic(d, path, caption, width=6.5):
    q = d.add_paragraph()
    q.paragraph_format.space_before = Pt(3)
    q.paragraph_format.space_after = Pt(3)
    q.paragraph_format.keep_with_next = True
    q.alignment = WD_ALIGN_PARAGRAPH.CENTER
    q.add_run().add_picture(str(path), width=Inches(width))
    note(d, caption)


def calc(n):
    storage = 2 * n * 1.1376 / FACTOR * .118
    replay = n * .9 / FACTOR * .5
    requests = n * .004
    variable = 4.72 + storage + replay + requests
    return dict(n=n, new_gb=n*1.1376, retained_gb=2*n*1.1376,
                storage_gib=2*n*1.1376/FACTOR,
                storage=storage, replay=replay, requests=requests,
                a=245+variable, b=689+variable,
                a_year=2499+variable*12, b_year=2499+444*12+variable*12)


