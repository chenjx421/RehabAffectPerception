def _clear_body(document: Document) -> None:
    body = document._element.body
    for child in list(body):
        if child.tag != qn("w:sectPr"):
            body.remove(child)


def _set_run(run, size: float, color: RGBColor, bold: bool = False) -> None:
    run.font.name = FONT
    run._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    run.font.size = Pt(size)
    run.font.color.rgb = color
    run.bold = bold


def _add_title(document: Document, text: str) -> None:
    paragraph = document.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.paragraph_format.space_after = Pt(4)
    run = paragraph.add_run(text)
    _set_run(run, 17, INK, True)


def _add_subtitle(document: Document, text: str) -> None:
    paragraph = document.add_paragraph()
    paragraph.alignment = WD_ALIGN_PARAGRAPH.CENTER
    paragraph.paragraph_format.space_after = Pt(10)
    run = paragraph.add_run(text)
    _set_run(run, 10.5, MUTED, False)


def _add_heading(document: Document, text: str) -> None:
    paragraph = document.add_paragraph()
    paragraph.paragraph_format.space_before = Pt(8)
    paragraph.paragraph_format.space_after = Pt(3)
    paragraph.paragraph_format.keep_with_next = True
    run = paragraph.add_run(text)
    _set_run(run, 14, BLUE, True)


def _add_body(document: Document, text: str) -> None:
    paragraph = document.add_paragraph()
    paragraph.paragraph_format.space_after = Pt(4)
    paragraph.paragraph_format.line_spacing = 1.16
    run = paragraph.add_run(text)
    _set_run(run, 10.5, INK, False)


def _add_bullet(document: Document, text: str) -> None:
    paragraph = document.add_paragraph(style="List Bullet")
    paragraph.paragraph_format.space_after = Pt(2)
    paragraph.paragraph_format.line_spacing = 1.12
    run = paragraph.add_run(text)
    _set_run(run, 10, INK, False)


def _append_table(document: Document, prototype):
    body = document._element.body
    table_element = deepcopy(prototype)
    section_properties = body.sectPr
    body.insert(body.index(section_properties), table_element)
    return document.tables[-1]


def _clear_paragraph(paragraph) -> None:
    paragraph.clear()
    paragraph.paragraph_format.space_before = Pt(0)
    paragraph.paragraph_format.space_after = Pt(0)
    paragraph.paragraph_format.line_spacing = 1.0


def _set_cell(cell, text: str, size: float, bold: bool = False) -> None:
    while len(cell.paragraphs) > 1:
        paragraph = cell.paragraphs[-1]
        cell._element.remove(paragraph._element)
    paragraph = cell.paragraphs[0]
    _clear_paragraph(paragraph)
    run = paragraph.add_run(text)
    _set_run(run, size, INK, bold)


def _set_row_cant_split(row) -> None:
    properties = row._tr.get_or_add_trPr()
    marker = properties.find(qn("w:cantSplit"))
    if marker is None:
        marker = OxmlElement("w:cantSplit")
        properties.append(marker)


def _set_repeat_header(row) -> None:
    properties = row._tr.get_or_add_trPr()
    marker = properties.find(qn("w:tblHeader"))
    if marker is None:
        marker = OxmlElement("w:tblHeader")
        properties.append(marker)
    marker.set(qn("w:val"), "true")


def _fill_callout(table, lines: list[str]) -> None:
    cell = table.cell(0, 0)
    while len(cell.paragraphs) < 3:
        cell.add_paragraph()
    while len(cell.paragraphs) > 3:
        cell._element.remove(cell.paragraphs[-1]._element)
    for index, text in enumerate(lines):
        paragraph = cell.paragraphs[index]
        _clear_paragraph(paragraph)
        paragraph.paragraph_format.space_after = Pt(2 if index < 2 else 0)
        run = paragraph.add_run(text)
        _set_run(run, 10.5 if index == 0 else 10, BLUE if index == 0 else INK, index == 0)


def _fill_grid(table, rows: list[list[str]], header_size: float = 9, body_size: float = 8.5) -> None:
    if len(table.rows) != len(rows):
        raise ValueError(f"table row mismatch: {len(table.rows)} != {len(rows)}")
    for row_index, values in enumerate(rows):
        if len(table.columns) != len(values):
            raise ValueError(f"table column mismatch: {len(table.columns)} != {len(values)}")
        for column_index, text in enumerate(values):
            bold = row_index == 0
            if row_index > 0 and column_index == 0 and len(table.columns) in {2, 4}:
                bold = True
            _set_cell(
                table.cell(row_index, column_index),
                text,
                header_size if row_index == 0 else body_size,
                bold,
            )
        _set_row_cant_split(table.rows[row_index])
    _set_repeat_header(table.rows[0])
    for cell in table.rows[0].cells:
        for paragraph in cell.paragraphs:
            paragraph.paragraph_format.keep_with_next = True


def _build_lesson(template_tables, lesson: dict, output_dir: Path = OUTPUT_DIR) -> Path:
    document = Document(TEMPLATE_PATH)
    _clear_body(document)
    document.core_properties.title = f"第 {lesson['number']:02d} 节：{lesson['title']}"
    document.core_properties.subject = "从人工智能到具身智能 15 节课程"
    document.core_properties.keywords = "人工智能, 具身智能, 校园机器人, 课程设计"

    _add_title(document, f"第 {lesson['number']:02d} 节：{lesson['title']}")
    _add_subtitle(document, lesson["subtitle"])

    _add_heading(document, "一、本节课定位")
    for paragraph in lesson["positioning"]:
        _add_body(document, paragraph)
    callout = _append_table(document, template_tables[0])
    _fill_callout(callout, ["本节与具身智能的关系", *lesson["embodied"]])

    _add_heading(document, "二、学习目标")
    for item in lesson["goals"]:
        _add_bullet(document, item)

    _add_heading(document, "三、核心知识点")
    for item in lesson["knowledge"]:
        _add_bullet(document, item)

    _add_heading(document, "四、PPT 页面建议")
    ppt_table = _append_table(document, template_tables[1])
    _fill_grid(ppt_table, [["页码", "页面标题", "页面内容"], *lesson["ppt"]])

    _add_heading(document, "五、90 分钟详细流程")
    flow_table = _append_table(document, template_tables[2])
    _fill_grid(
        flow_table,
        [["时间", "环节", "教师做什么", "学生做什么"], *lesson["flow"]],
    )

    _add_heading(document, "六、教师讲稿参考")
    for paragraph in lesson["script"]:
        _add_body(document, paragraph)

    _add_heading(document, "七、课堂任务单")
    for item in lesson["task"]:
        _add_bullet(document, item)

    _add_heading(document, "八、教师追问与引导")
    qa_table = _append_table(document, template_tables[3])
    _fill_grid(qa_table, [["学生可能回答", "教师追问/引导"], *lesson["qa"]])

    _add_heading(document, "九、材料准备")
    for item in lesson["materials"]:
        _add_bullet(document, item)

    _add_heading(document, "十、安全与应急")
    for item in lesson["safety"]:
        _add_bullet(document, item)

    _add_heading(document, "十一、评价标准")
    for item in lesson["evaluation"]:
        _add_bullet(document, item)

    _add_heading(document, "十二、课后延伸")
    _add_body(document, lesson["extension"])

    output = output_dir / f"第{lesson['number']:02d}节_{lesson['title']}.docx"
    document.save(output)
    return output


def main() -> None:
    if not TEMPLATE_PATH.exists():
        raise FileNotFoundError(f"Template not found: {TEMPLATE_PATH}")
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    template_document = Document(TEMPLATE_PATH)
    template_tables = [deepcopy(table._tbl) for table in template_document.tables]
    if [len(table.rows) for table in template_document.tables] != [1, 9, 8, 4]:
        raise ValueError("Unexpected template table structure")

    outputs = [_build_lesson(template_tables, lesson) for lesson in LESSONS]
    print("15-lesson course map:")
    for item in COURSE_MAP:
        print(f"- {item}")
    print("\nGenerated batch 1:")
    for output in outputs:
        print(output)


if __name__ == "__main__":
    main()
